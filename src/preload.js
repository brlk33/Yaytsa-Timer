const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('focusApi', {
  load: () => ipcRenderer.invoke('data:load'),
  save: (partial) => ipcRenderer.invoke('data:save', partial),
  saveSync: (partial) => ipcRenderer.sendSync('data:save-sync', partial),
  showAlert: (data) => ipcRenderer.send('alert:show', data),
  closeAlert: () => ipcRenderer.send('alert:close'),
  onAlertAction: (cb) => ipcRenderer.on('alert-action', (_e, a) => cb(a)),
  updateTray: (state) => ipcRenderer.send('tray:update', state),
  onTrayAction: (cb) => ipcRenderer.on('tray-action', (_e, a) => cb(a)),
  quit: () => ipcRenderer.send('app:quit'),
  log: (m) => ipcRenderer.send('log', m),
  onUpdateReady: (cb) => ipcRenderer.on('update-ready', (_e, v) => cb(v)),
  installUpdate: () => ipcRenderer.send('update:install'),
  notify: (title, body) => ipcRenderer.send('notify', { title, body }),
  progress: (value, paused) => ipcRenderer.send('progress', { value, paused }),
  title: (t) => ipcRenderer.send('title', t),
  theme: (t) => ipcRenderer.send('theme', t),
  systemDark: () => ipcRenderer.invoke('system-dark'),
  onSystemTheme: (cb) => ipcRenderer.on('system-theme-changed', (_e, dark) => cb(dark)),
  alwaysOnTop: (on) => ipcRenderer.send('always-on-top', on),
  focusWindow: () => ipcRenderer.send('focus-window'),
  exportCsv: (csv, name) => ipcRenderer.invoke('export-csv', { csv, name }),
  openDataFolder: () => ipcRenderer.send('open-data-folder'),
});
